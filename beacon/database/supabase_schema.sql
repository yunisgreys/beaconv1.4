-- v1.3: at most 2 "Mother" accounts per student (pending or approved).
CREATE OR REPLACE FUNCTION beacon_limit_mother_links() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    taken INTEGER;
BEGIN
    IF lower(btrim(NEW.relationship)) <> 'mother' OR NEW.status NOT IN ('pending','approved') THEN
        RETURN NEW;
    END IF;
    -- Serialise concurrent requests for the same student.
    PERFORM pg_advisory_xact_lock(hashtext('beacon_mother_limit'), NEW.student_id);
    SELECT COUNT(*) INTO taken
      FROM parent_student_links
     WHERE student_id = NEW.student_id
       AND lower(btrim(relationship)) = 'mother'
       AND status IN ('pending','approved')
       AND id IS DISTINCT FROM NEW.id;
    IF taken >= 2 THEN
        RAISE EXCEPTION 'MOTHER_LIMIT: This student already has 2 Mother accounts linked.'
            USING ERRCODE = 'P0001';
    END IF;
    RETURN NEW;
END $$;
CREATE OR REPLACE TRIGGER trg_psl_mother_limit
    BEFORE INSERT OR UPDATE OF relationship, status, student_id ON parent_student_links
    FOR EACH ROW EXECUTE FUNCTION beacon_limit_mother_links();

