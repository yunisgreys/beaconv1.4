-- Replaces MySQL's "ON UPDATE CURRENT_TIMESTAMP".
CREATE OR REPLACE FUNCTION beacon_touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := LOCALTIMESTAMP(0);
    RETURN NEW;
END $$;

-- E-mails are stored lowercase so logins are case-insensitive (as in MySQL).
CREATE OR REPLACE FUNCTION beacon_lowercase_email() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.email := lower(btrim(NEW.email));
    RETURN NEW;
END $$;

