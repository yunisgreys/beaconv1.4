-- ---------------------------------------------------------------------
-- 8. Early-warning view, updated_at / e-mail triggers, security
-- ---------------------------------------------------------------------

CREATE OR REPLACE VIEW v_wellbeing_signals WITH (security_invoker = true) AS
SELECT
    s.id AS student_id,
    s.section_id,
    (SELECT COUNT(*) FROM incident_reports ir
      WHERE ir.student_id = s.id
        AND ir.category IN ('emotional','mental_health','behavioral','peer_conflict')
        AND ir.observed_at >= CURRENT_DATE - INTERVAL '30 days')     AS incidents_30d,
    (SELECT COUNT(*) FROM clinic_visits cv
      WHERE cv.student_id = s.id
        AND cv.arrived_at >= CURRENT_DATE - INTERVAL '30 days')      AS clinic_visits_30d,
    (SELECT COUNT(*) FROM clinic_visits cv
      WHERE cv.student_id = s.id AND cv.is_sensitive = 1
        AND cv.arrived_at >= CURRENT_DATE - INTERVAL '30 days')      AS sensitive_visits_30d,
    (SELECT COUNT(*) FROM attendance a
      WHERE a.student_id = s.id AND a.status = 'absent'
        AND a.att_date >= CURRENT_DATE - INTERVAL '30 days')         AS absences_30d,
    (SELECT COUNT(*) FROM guidance_cases gc
      WHERE gc.student_id = s.id AND gc.status <> 'closed')          AS open_cases
FROM students s
WHERE s.status = 'enrolled';

DO $$
DECLARE
    t TEXT;
BEGIN
    -- updated_at triggers
    FOREACH t IN ARRAY ARRAY['users','students','attendance','guidance_cases','case_notes',
                             'interventions','medical_profiles','inventory_items','staff_registry'] LOOP
        EXECUTE format('CREATE OR REPLACE TRIGGER trg_%1$s_touch BEFORE UPDATE ON %1$I
                        FOR EACH ROW EXECUTE FUNCTION beacon_touch_updated_at()', t);
    END LOOP;

    -- lowercase e-mails
    FOREACH t IN ARRAY ARRAY['users','login_attempts','staff_registry'] LOOP
        EXECUTE format('CREATE OR REPLACE TRIGGER trg_%1$s_email BEFORE INSERT OR UPDATE OF email ON %1$I
                        FOR EACH ROW EXECUTE FUNCTION beacon_lowercase_email()', t);
    END LOOP;

    -- Lock every BEACON table away from the public Supabase REST API.
    -- RLS on + no policies = anon/authenticated keys see nothing.
    -- The PHP server connects as postgres, which owns the tables and is not affected.
    FOREACH t IN ARRAY ARRAY['roles','users','login_attempts','password_change_requests','sections',
                             'section_teachers','students','parent_student_links','attendance','grades',
                             'commendations','guidance_cases','incident_reports','case_notes','interventions',
                             'intervention_updates','consent_events','counseling_sessions','medical_profiles',
                             'clinic_passes','clinic_visits','inventory_items','medications_administered',
                             'inventory_movements','notices','notice_acknowledgements','audit_logs','staff_registry'] LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
            EXECUTE format('REVOKE ALL ON TABLE %I FROM anon', t);
        END IF;
        IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
            EXECUTE format('REVOKE ALL ON TABLE %I FROM authenticated', t);
        END IF;
    END LOOP;

    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
        REVOKE ALL ON v_wellbeing_signals FROM anon;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
        REVOKE ALL ON v_wellbeing_signals FROM authenticated;
    END IF;
END $$;

